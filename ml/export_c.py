import argparse
import os

import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from train import DEFAULT_CSV, LABELS, load

DEFAULT_OUT = os.path.join(os.path.dirname(__file__), "..", "firmware", "color-classifier", "color_model.h")


def fmt(values):
    return ", ".join(f"{v:.8e}f" for v in values)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--csv", default=DEFAULT_CSV)
    parser.add_argument("--out", default=DEFAULT_OUT)
    parser.add_argument("--reference", help="also save the model's predictions on the training data here")
    args = parser.parse_args()

    X, y, _ = load(args.csv, use_clear=True)
    pipe = make_pipeline(StandardScaler(), LogisticRegression(max_iter=1000)).fit(X, y)
    scaler, lr = pipe[0], pipe[1]
    assert list(lr.classes_) == list(range(len(LABELS)))
    print(f"trained on {len(y)} samples, training accuracy {pipe.score(X, y):.3f}")

    rows = ",\n    ".join("{" + fmt(w) + "}" for w in lr.coef_)
    labels = ", ".join(f'"{name}"' for name in LABELS)
    text = f"""// generated by ml/export_c.py from {os.path.basename(args.csv)} ({len(y)} samples). Do not edit by hand.
#pragma once
#include <math.h>

#define COLOR_N_FEATURES {X.shape[1]}
#define COLOR_N_CLASSES {len(LABELS)}

static const char* const COLOR_LABELS[COLOR_N_CLASSES] = {{{labels}}};
static const float COLOR_MEAN[COLOR_N_FEATURES] = {{{fmt(scaler.mean_)}}};
static const float COLOR_SCALE[COLOR_N_FEATURES] = {{{fmt(scaler.scale_)}}};
static const float COLOR_W[COLOR_N_CLASSES][COLOR_N_FEATURES] = {{
    {rows}
}};
static const float COLOR_B[COLOR_N_CLASSES] = {{{fmt(lr.intercept_)}}};

// returns the class index (0 = {LABELS[0]}, ...) or -1 if the reading is unusable.
// *confidence is the softmax probability of the winning class.
static inline int classify_color(int r, int g, int b, int clear, float* confidence) {{
    float total = (float)(r + g + b);
    if (total <= 0.0f) return -1;

    float x[COLOR_N_FEATURES] = {{r / total, g / total, b / total, logf(1.0f + (float)clear)}};
    float logit[COLOR_N_CLASSES];
    float best = -1e30f;
    for (int c = 0; c < COLOR_N_CLASSES; c++) {{
        float z = COLOR_B[c];
        for (int i = 0; i < COLOR_N_FEATURES; i++) {{
            z += COLOR_W[c][i] * (x[i] - COLOR_MEAN[i]) / COLOR_SCALE[i];
        }}
        logit[c] = z;
        if (z > best) best = z;
    }}

    float sum = 0.0f;
    int winner = 0;
    for (int c = 0; c < COLOR_N_CLASSES; c++) {{
        logit[c] = expf(logit[c] - best);
        sum += logit[c];
        if (logit[c] > logit[winner]) winner = c;
    }}
    if (confidence) *confidence = logit[winner] / sum;
    return winner;
}}
"""
    out = os.path.abspath(args.out)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write(text)
    print(f"wrote {out}")

    if args.reference:  # scikit-learn predictions, to check the C code against
        np.savetxt(os.path.abspath(args.reference), pipe.predict(X), fmt="%d")


if __name__ == "__main__":
    main()
